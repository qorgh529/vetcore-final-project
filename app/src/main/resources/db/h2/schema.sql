DROP TABLE reservations IF EXISTS;
DROP TABLE treatment_schedules IF EXISTS;
DROP TABLE partner_hospitals IF EXISTS;
DROP TABLE users IF EXISTS;
DROP TABLE vet_specialties IF EXISTS;
DROP TABLE vets IF EXISTS;
DROP TABLE specialties IF EXISTS;
DROP TABLE visits IF EXISTS;
DROP TABLE pets IF EXISTS;
DROP TABLE types IF EXISTS;
DROP TABLE owners IF EXISTS;


CREATE TABLE vets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30),
  last_name  VARCHAR(30)
);
CREATE INDEX vets_last_name ON vets (last_name);

CREATE TABLE specialties (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80)
);
CREATE INDEX specialties_name ON specialties (name);

CREATE TABLE vet_specialties (
  vet_id       INTEGER NOT NULL,
  specialty_id INTEGER NOT NULL
);
ALTER TABLE vet_specialties ADD CONSTRAINT fk_vet_specialties_vets FOREIGN KEY (vet_id) REFERENCES vets (id);
ALTER TABLE vet_specialties ADD CONSTRAINT fk_vet_specialties_specialties FOREIGN KEY (specialty_id) REFERENCES specialties (id);

CREATE TABLE types (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80)
);
CREATE INDEX types_name ON types (name);

CREATE TABLE owners (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30),
  last_name  VARCHAR_IGNORECASE(30),
  address    VARCHAR(255),
  city       VARCHAR(80),
  telephone  VARCHAR(20)
);
CREATE INDEX owners_last_name ON owners (last_name);

CREATE TABLE pets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR_IGNORECASE(30),
  birth_date DATE,
  type_id    INTEGER NOT NULL,
  owner_id   INTEGER
);
ALTER TABLE pets ADD CONSTRAINT fk_pets_owners FOREIGN KEY (owner_id) REFERENCES owners (id);
ALTER TABLE pets ADD CONSTRAINT fk_pets_types FOREIGN KEY (type_id) REFERENCES types (id);
ALTER TABLE pets ADD CONSTRAINT unique_owner_pet_name UNIQUE (owner_id, name);
CREATE INDEX pets_name ON pets (name);

CREATE TABLE visits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INTEGER,
  visit_date  DATE,
  description VARCHAR(255)
);
ALTER TABLE visits ADD CONSTRAINT fk_visits_pets FOREIGN KEY (pet_id) REFERENCES pets (id);
CREATE INDEX visits_pet_id ON visits (pet_id);

CREATE TABLE users (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     VARCHAR(30)  NOT NULL,
  password     VARCHAR(100) NOT NULL,
  display_name VARCHAR(30)  NOT NULL,
  role         VARCHAR(20)  NOT NULL,
  created_at   TIMESTAMP    NOT NULL
);
ALTER TABLE users ADD CONSTRAINT uk_users_username UNIQUE (username);

CREATE TABLE partner_hospitals (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR(80) NOT NULL,
  region    VARCHAR(30) NOT NULL,
  address   VARCHAR(255),
  telephone VARCHAR(20)
);
CREATE INDEX partner_hospitals_region ON partner_hospitals (region);

CREATE TABLE treatment_schedules (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id      INTEGER     NOT NULL,
  treatment_name   VARCHAR(80) NOT NULL,
  treatment_date   DATE        NOT NULL,
  start_time       TIME        NOT NULL,
  capacity         INTEGER     NOT NULL,
  reserved_count   INTEGER     DEFAULT 0 NOT NULL,
  booking_opens_at TIMESTAMP   NOT NULL,
  CONSTRAINT ck_schedules_seats CHECK (reserved_count >= 0 AND reserved_count <= capacity)
);
ALTER TABLE treatment_schedules ADD CONSTRAINT fk_schedules_hospital FOREIGN KEY (hospital_id) REFERENCES partner_hospitals (id);
CREATE INDEX treatment_schedules_date ON treatment_schedules (treatment_date);

CREATE TABLE reservations (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id INTEGER     NOT NULL,
  user_id     INTEGER     NOT NULL,
  pet_name    VARCHAR(30) NOT NULL,
  memo        VARCHAR(255),
  status      VARCHAR(20) NOT NULL,
  created_at  TIMESTAMP   NOT NULL,
  updated_at  TIMESTAMP   NOT NULL
);
ALTER TABLE reservations ADD CONSTRAINT fk_reservations_schedule FOREIGN KEY (schedule_id) REFERENCES treatment_schedules (id);
ALTER TABLE reservations ADD CONSTRAINT fk_reservations_user FOREIGN KEY (user_id) REFERENCES users (id);
ALTER TABLE reservations ADD CONSTRAINT uk_reservations_schedule_user UNIQUE (schedule_id, user_id);
CREATE INDEX reservations_user ON reservations (user_id);

-- Spring Session JDBC (login sessions shared by all instances)
CREATE TABLE SPRING_SESSION (
  PRIMARY_ID            CHAR(36) NOT NULL,
  SESSION_ID            CHAR(36) NOT NULL,
  CREATION_TIME         BIGINT   NOT NULL,
  LAST_ACCESS_TIME      BIGINT   NOT NULL,
  MAX_INACTIVE_INTERVAL INT      NOT NULL,
  EXPIRY_TIME           BIGINT   NOT NULL,
  PRINCIPAL_NAME        VARCHAR(100),
  CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
  SESSION_PRIMARY_ID CHAR(36)      NOT NULL,
  ATTRIBUTE_NAME     VARCHAR(200)  NOT NULL,
  ATTRIBUTE_BYTES    LONGVARBINARY NOT NULL,
  CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
  CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS vets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT
);
CREATE INDEX IF NOT EXISTS idx_vets_last_name ON vets (last_name);

CREATE TABLE IF NOT EXISTS specialties (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS idx_specialties_name ON specialties (name);

CREATE TABLE IF NOT EXISTS vet_specialties (
  vet_id       INT NOT NULL REFERENCES vets (id),
  specialty_id INT NOT NULL REFERENCES specialties (id),
  UNIQUE (vet_id, specialty_id)
);

CREATE TABLE IF NOT EXISTS types (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS idx_types_name ON types (name);

CREATE TABLE IF NOT EXISTS owners (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT,
  address    TEXT,
  city       TEXT,
  telephone  TEXT
);
CREATE INDEX IF NOT EXISTS idx_owners_last_name ON owners (last_name);

CREATE TABLE IF NOT EXISTS pets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT,
  birth_date DATE,
  type_id    INT NOT NULL REFERENCES types (id),
  owner_id   INT REFERENCES owners (id)
);
CREATE INDEX IF NOT EXISTS idx_pets_name ON pets (name);
CREATE INDEX IF NOT EXISTS idx_pets_owner_id ON pets (owner_id);
CREATE UNIQUE INDEX IF NOT EXISTS unique_owner_pet_name ON pets (owner_id, LOWER(name));

CREATE TABLE IF NOT EXISTS visits (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INT REFERENCES pets (id),
  visit_date  DATE,
  description TEXT
);
CREATE INDEX IF NOT EXISTS idx_visits_pet_id ON visits (pet_id);

CREATE TABLE IF NOT EXISTS users (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     TEXT NOT NULL UNIQUE,
  password     TEXT NOT NULL,
  display_name TEXT NOT NULL,
  role         TEXT NOT NULL,
  created_at   TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS partner_hospitals (
  id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      TEXT NOT NULL,
  region    TEXT NOT NULL,
  address   TEXT,
  telephone TEXT
);
CREATE INDEX IF NOT EXISTS idx_partner_hospitals_region ON partner_hospitals (region);

CREATE TABLE IF NOT EXISTS treatment_schedules (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id      INT NOT NULL REFERENCES partner_hospitals (id),
  treatment_name   TEXT NOT NULL,
  treatment_date   DATE NOT NULL,
  start_time       TIME NOT NULL,
  capacity         INT NOT NULL,
  reserved_count   INT NOT NULL DEFAULT 0,
  booking_opens_at TIMESTAMP NOT NULL,
  CONSTRAINT ck_schedules_seats CHECK (reserved_count >= 0 AND reserved_count <= capacity)
);
CREATE INDEX IF NOT EXISTS idx_treatment_schedules_date ON treatment_schedules (treatment_date);

CREATE TABLE IF NOT EXISTS reservations (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id INT NOT NULL REFERENCES treatment_schedules (id),
  user_id     INT NOT NULL REFERENCES users (id),
  pet_name    TEXT NOT NULL,
  memo        TEXT,
  status      TEXT NOT NULL,
  created_at  TIMESTAMP NOT NULL,
  updated_at  TIMESTAMP NOT NULL,
  UNIQUE (schedule_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_reservations_user ON reservations (user_id);

-- Spring Session JDBC (login sessions shared by all instances)
CREATE TABLE IF NOT EXISTS SPRING_SESSION (
  PRIMARY_ID            CHAR(36) NOT NULL,
  SESSION_ID            CHAR(36) NOT NULL,
  CREATION_TIME         BIGINT NOT NULL,
  LAST_ACCESS_TIME      BIGINT NOT NULL,
  MAX_INACTIVE_INTERVAL INT NOT NULL,
  EXPIRY_TIME           BIGINT NOT NULL,
  PRINCIPAL_NAME        VARCHAR(100),
  CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX IF NOT EXISTS SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX IF NOT EXISTS SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE IF NOT EXISTS SPRING_SESSION_ATTRIBUTES (
  SESSION_PRIMARY_ID CHAR(36) NOT NULL,
  ATTRIBUTE_NAME     VARCHAR(200) NOT NULL,
  ATTRIBUTE_BYTES    BYTEA NOT NULL,
  CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
  CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE
);
